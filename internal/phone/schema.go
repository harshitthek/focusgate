package phone

const schema = `
CREATE TABLE IF NOT EXISTS preferences (
	id INTEGER PRIMARY KEY CHECK(id=1), offline INTEGER NOT NULL DEFAULT 0,
	alerts INTEGER NOT NULL DEFAULT 0, mode TEXT NOT NULL DEFAULT 'normal',
	last_digest INTEGER NOT NULL DEFAULT 0, cursor TEXT NOT NULL DEFAULT '0',
	legacy_imported INTEGER NOT NULL DEFAULT 0
);
INSERT OR IGNORE INTO preferences(id) VALUES(1);
CREATE TABLE IF NOT EXISTS feeds (
	id TEXT PRIMARY KEY, url TEXT NOT NULL, name TEXT NOT NULL,
	paused INTEGER NOT NULL DEFAULT 0, assess INTEGER NOT NULL DEFAULT 0,
	revision INTEGER NOT NULL DEFAULT 0, generation INTEGER NOT NULL DEFAULT 0,
	refreshed INTEGER NOT NULL DEFAULT 0, removed INTEGER NOT NULL DEFAULT 0,
	etag TEXT NOT NULL DEFAULT '', modified TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS inbox (
	id TEXT PRIMARY KEY, feed_id TEXT NOT NULL, title TEXT NOT NULL, url TEXT NOT NULL,
	snippet TEXT NOT NULL, published INTEGER NOT NULL, status INTEGER NOT NULL DEFAULT 0,
	priority INTEGER NOT NULL, delivery INTEGER NOT NULL DEFAULT 0,
	digest INTEGER NOT NULL DEFAULT 0, decision TEXT NOT NULL DEFAULT '',
	received INTEGER NOT NULL DEFAULT 0, snapshot_seen INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS phone_inbox_order ON inbox(status,priority DESC,published DESC,id);
CREATE TABLE IF NOT EXISTS seen (id TEXT PRIMARY KEY, seen_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS outbox (
	seq INTEGER PRIMARY KEY AUTOINCREMENT, op TEXT NOT NULL UNIQUE, kind TEXT NOT NULL,
	entity TEXT NOT NULL, base INTEGER NOT NULL, data TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS outbox_entity ON outbox(entity,kind);
CREATE TABLE IF NOT EXISTS feed_snapshot_members(id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS feed_conflicts(id TEXT PRIMARY KEY, data TEXT NOT NULL);
`
